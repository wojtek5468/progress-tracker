LABELS = {'Taper': 'odpuszczenie', 'Zawody': 'start lub test 1RM'}


def clean(item):
    return {k: item[k] for k in KEEP if item.get(k) is not None}


def main(seed_path, out_path):
    seed = json.load(open(seed_path, encoding='utf-8'))
    programs = {p['id']: p for p in seed['programs']}
    templates = []
    for program_id, first, last, meta in SEGMENTS:
        weeks = [w for w in programs[program_id]['weeks'] if first <= w['number'] <= last]
        out_weeks = []
        for w in weeks:
            sessions = []
            for s in w['sessions']:
                blocks = [{'type': b['type'], 'items': [clean(i) for i in b['items']]} for b in s['blocks']]
                sessions.append({'blocks': [b for b in blocks if b['items']]})
            week = {'sessions': sessions}
            if w.get('label'):
                week['label'] = LABELS.get(w['label'], w['label'])
            out_weeks.append(week)
        templates.append({
            **meta, 'place': 'gym', 'audience': 'men', 'source': 'coach',
            'perWeek': max(len(w['sessions']) for w in out_weeks), 'weeks': out_weeks,
        })
    with open(out_path, 'w', encoding='utf-8') as f:
        f.write('// Generated by tools/export_templates.py from a real coached training year.\n')
        f.write('// Structure only (exercises, sets, reps, %1RM, RIR, tempo, rest); no loads, dates or results.\n')
        f.write('export const COACH_TEMPLATES = ')
        f.write(json.dumps(templates, ensure_ascii=False, separators=(',', ':')))
        f.write(';\n')


if __name__ == '__main__':
    main(*sys.argv[1:3])
