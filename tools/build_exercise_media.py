"""Builds app/js/exercise-media.js: pictures and muscles for exercises in our catalogue.

Source: free-exercise-db (https://github.com/yuhonas/free-exercise-db), released into the
public domain (Unlicense). tools/fedb_map.json maps our exercise ids to its ids.

    python3 tools/build_exercise_media.py [exercises.json]

Without an argument the dataset is downloaded from GitHub.
"""
import json
import sys
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = 'https://raw.githubusercontent.com/yuhonas/free-exercise-db/main/dist/exercises.json'

# free-exercise-db muscle names -> our muscle keys (labels live in the generated module).
MUSCLES = {
    'quadriceps': 'quads', 'hamstrings': 'hamstrings', 'glutes': 'glutes', 'calves': 'calves',
    'adductors': 'adductors', 'abductors': 'abductors', 'abdominals': 'abs', 'lower back': 'lowerBack',
    'lats': 'lats', 'middle back': 'midBack', 'traps': 'traps', 'chest': 'chest', 'shoulders': 'shoulders',
    'biceps': 'biceps', 'triceps': 'triceps', 'forearms': 'forearms', 'neck': 'neck',
}
EQUIPMENT = {
    'barbell': 'sztanga', 'e-z curl bar': 'sztanga', 'dumbbell': 'hantle', 'kettlebells': 'kettlebell',
    'cable': 'wyciąg', 'machine': 'maszyna', 'body only': 'bez sprzętu', 'bands': 'guma',
    'medicine ball': 'piłka', 'exercise ball': 'piłka', 'foam roll': 'wałek', 'other': 'inny',
}


def main():
    if len(sys.argv) > 1:
        data = json.loads(Path(sys.argv[1]).read_text())
    else:
        with urllib.request.urlopen(SRC) as r:
            data = json.load(r)
    by_id = {x['id']: x for x in data}
    mapping = json.loads((ROOT / 'tools' / 'fedb_map.json').read_text())
    rows = {}
    for ours, theirs in sorted(mapping.items()):
        x = by_id[theirs]
        rows[ours] = [
            theirs,
            [MUSCLES[m] for m in x['primaryMuscles'] if m in MUSCLES],
            [MUSCLES[m] for m in x['secondaryMuscles'] if m in MUSCLES],
            EQUIPMENT.get(x['equipment'] or 'other', 'inny'),
            len(x['images']),
        ]
    body = ',\n'.join(f'  {json.dumps(k)}: {json.dumps(v, ensure_ascii=False)}' for k, v in rows.items())
    out = f'''// Generated by tools/build_exercise_media.py; do not edit by hand.
// Pictures and muscles from free-exercise-db (github.com/yuhonas/free-exercise-db), public domain (Unlicense).
// our id -> [free-exercise-db id, primary muscles, secondary muscles, equipment, number of pictures]
export const MEDIA = {{
{body},
}};
'''
    (ROOT / 'app' / 'js' / 'exercise-media.js').write_text(out)
    print(f'{len(rows)} exercises')


if __name__ == '__main__':
    main()
